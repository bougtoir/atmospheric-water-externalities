"""Gate 4 sensitivity report generated from canonical per-case WRF outputs."""
import json, glob, os
import numpy as np, pandas as pd

S = json.load(open("results/wrf/programme_summary.json"))
C = S["cases"]
rows = []
for c, v in C.items():
    p = json.load(open(f"results/wrf/{c}/paired.json"))["paired"]
    t = json.load(open(f"results/wrf/{c}/run_config.json"))["turbines"]
    w = p["WIND"]
    noise = [p[k] for k in p if k.startswith("CTLPERT")]
    r = dict(case=c, regime=v["regime"], capacity_GW=t["capacity_mw"] / 1e3,
             n_turbines=t["n_turbines"], mean_power_GW=v["mean_power_GW"],
             n_no_wind=v["n_no_wind_ensemble"], n_outside=v["n_outside"], n_countries=v["n_countries"],
             dP_inner_total_pct=v["dP_inner_total_pct"])
    for f in ("hub_wind", "PBLH", "E_acc_mm", "P_acc_mm"):
        r[f"{f}_farm_WIND"] = w[f]["farm_cells_mean"]
        r[f"{f}_farm_noise_absmax"] = max(abs(n[f]["farm_cells_mean"]) for n in noise)
        for b, x in v["ratios"][f].items():
            r[f"{f}_ratio_{b}"] = x
    rows.append(r)
d = pd.DataFrame(rows).sort_values("case")
d.to_csv("results/wrf/sensitivity_summary.csv", index=False)

def rng(col, fmt="{:.2f}"):
    return f"{fmt.format(d[col].min())}–{fmt.format(d[col].max())}"

L = ["# WRF sensitivity report", "",
     "Generated by `scripts/wrf/w17_sensitivity_report.py` from `results/wrf/<case>/{paired,run_config}.json` and "
     "`results/wrf/programme_summary.json`. Values are WRF model-conditional contrasts (WIND − CONTROL) for this "
     "configuration; they are not observed real-world effects.", "",
     "## 1. Sensitivities that were sampled", "",
     f"| dimension | how sampled | n |", "|---|---|---|",
     f"| meteorological regime / event | {', '.join(sorted(set(d.regime)))} events, pre-selected without treatment outputs | {len(d)} |",
     f"| internal variability | CONTROL + deterministic-seed IC perturbations (0.01 K, T and THM, lowest 10 levels) | {int(d.n_no_wind.min())}–{int(d.n_no_wind.max())} no-wind members per event |",
     f"| installed fleet (inventory date) | EWW offshore inventory at each event date | {rng('capacity_GW', '{:.1f}')} GW, {d.n_turbines.min()}–{d.n_turbines.max()} turbines |", "",
     "## 2. Event-to-event spread of the contrast", "",
     "| case | regime | capacity GW | mean power GW | farm-cell Δhub wind (m/s) | max |noise| | farm-cell ΔPBLH (m) | max |noise| | near-farm hub S/N | far-field P S/N | countries outside PI |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
for _, r in d.iterrows():
    L.append(f"| {r.case} | {r.regime} | {r.capacity_GW:.1f} | {r.mean_power_GW:.1f} | {r.hub_wind_farm_WIND:+.3f} | "
             f"{r.hub_wind_farm_noise_absmax:.3f} | {r.PBLH_farm_WIND:+.1f} | {r.PBLH_farm_noise_absmax:.1f} | "
             f"{r.hub_wind_ratio_farm_0_30km:.2f} | {r.P_acc_mm_ratio_far_gt150km:.2f} | {r.n_outside}/{r.n_countries} |")
L += ["",
      f"Across events the near-farm hub-wind signal-to-noise ratio ranges {rng('hub_wind_ratio_farm_0_30km')} while "
      f"the far-field (>150 km) precipitation ratio ranges {rng('P_acc_mm_ratio_far_gt150km')}. The local response "
      + ("has the same sign in every event and exceeds the largest no-wind farm-cell deviation" if
         ((np.sign(d.hub_wind_farm_WIND) == np.sign(d.hub_wind_farm_WIND.iloc[0])).all() and
          (d.hub_wind_farm_WIND.abs() > d.hub_wind_farm_noise_absmax).all()) else "is not consistent across events")
      + "; the far-field precipitation response is "
      + ("not distinguishable from internal variability in any event" if d.P_acc_mm_ratio_far_gt150km.max() < 1.5
         else "above the noise in at least one event") + ". Pooled country-event flags: "
      f"{S['pooled']['n_outside']}/{S['pooled']['n_tests']} (nominal expectation {S['pooled']['expected_outside']:.1f}).", "",
      "## 3. Sensitivities that were NOT sampled (scientific limitations, not technical blockers)", "",
      "| dimension | status | consequence |", "|---|---|---|",
      "| horizontal resolution (15 km only) | not run | farm wakes are sub-grid; near-farm magnitudes are resolution-dependent |",
      "| PBL / surface-layer scheme (MYNN only; Fitch requires MYNN) | not run | structural model uncertainty of [C] is not quantified |",
      "| Fitch TKE factor (0.25 only) | not run | the added-TKE source, and thus PBLH/mixing response, is not bracketed |",
      "| microphysics / convection (Thompson, Kain–Fritsch only) | not run | precipitation-response structural uncertainty not quantified |",
      "| domain extent / boundary placement | not run | far-field contrasts may be damped by specified lateral boundaries |",
      "| seasonal/climatological coverage (5-day JJA events only) | not run | no seasonal or long-term TAWE estimate is made |",
      "| country-isolated interventions | not run | no country-specific source attribution (see WRF_SOURCE_RECEPTOR_REPORT.md) |",
      "| ensemble size (≤4 no-wind members) | limited by compute | 95% prediction intervals are coarse; weak far-field signals cannot be excluded |", "",
      "These omissions bound the interpretation: the WRF results show a clear local response and no detectable "
      "cross-border precipitation response *within this single configuration*; they do not establish that no such "
      "response exists in other configurations or in the real atmosphere."]
open("docs/revision/WRF_SENSITIVITY_REPORT.md", "w").write("\n".join(L) + "\n")
print("wrote WRF_SENSITIVITY_REPORT.md", len(d), "cases")
