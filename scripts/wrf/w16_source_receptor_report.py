"""Gate 5: WRF-based source/receptor network ΔP_j = P_j(WIND) − P_j(CONTROL), rendered from canonical outputs.

Reads results/wrf/CASE/{country_signal_noise,supply_vs_wrf,country_precip}.csv for every case with a complete no-wind
ensemble (results/wrf/programme_summary.json). Writes results/wrf/source_receptor_wrf.csv and
docs/revision/WRF_SOURCE_RECEPTOR_REPORT.md. No hand-typed values.
"""
import json
import pandas as pd

S = json.load(open("results/wrf/programme_summary.json"))
rows = []
for c, v in S["cases"].items():
    sn = pd.read_csv(f"results/wrf/{c}/country_signal_noise.csv")
    sv = pd.read_csv(f"results/wrf/{c}/supply_vs_wrf.csv")[["country", "S_dP_kg"]]
    cp = pd.read_csv(f"results/wrf/{c}/country_precip.csv")
    cp = cp[cp.exp == "WIND"][["country", "area_km2", "P_control_kg", "dP_mm"]]
    d = sn.merge(sv, on="country").merge(cp, on="country")
    d.insert(0, "case", c); d.insert(1, "regime", v["regime"])
    d["dP_rel"] = d.dP_wind_kg / d.P_control_kg
    d["S_over_noise"] = d.S_dP_kg.abs() / d.pi_halfwidth_kg
    rows.append(d)
A = pd.concat(rows, ignore_index=True)
A.to_csv("results/wrf/source_receptor_wrf.csv", index=False)

n_ev = A.case.nunique(); flagged = A[A.outside_internal_variability]
rep = flagged.groupby("country").case.nunique()
L = ["# WRF source/receptor network (Gate 5)", "",
     "Generated by `scripts/wrf/w16_source_receptor_report.py` from `results/wrf/*/` (table: `results/wrf/source_receptor_wrf.csv`).", "",
     "## Estimand", "",
     "For receptor country j and event e: ΔP_j,e = P_j,e(WIND) − P_j,e(CONTROL), accumulated over the analysis window after",
     "24 h spin-up, inner domain only. The intervention is the whole offshore fleet (Fitch parameterisation, EWW inventory",
     "commissioned before the event). The contrast is model-conditional (evidence class [C]); it is not a real-world causal",
     "effect and is not an observation.", "",
     "## What the network can and cannot attribute", "",
     "- Source side: only all-fleet interventions were run. No country-isolated (single-owner) fleet experiment exists, so",
     "  ΔP_j cannot be split into contributions of individual source countries. Owner-resolved shares in the manuscript",
     "  remain [A] accounting quantities (moisture provenance), not [C] intervention effects. No attribution convention",
     "  (e.g. proportional to capacity) is applied, because Fitch effects are non-additive across interacting wakes.",
     "- Receptor side: ΔP_j is a change in atmospheric precipitation over country j. It is not a change in available",
     "  freshwater, soil moisture, groundwater recharge, agricultural drought or desertification; those require",
     "  land-surface and hydrological propagation that was not modelled beyond the WRF Noah land surface over five days.",
     "- Internal variability: each event has one WIND member and a four-member no-wind ensemble (CONTROL + CTLPERT_1..3).",
     "  ΔP_j,e is compared with the 95 % prediction interval of the no-wind ensemble; flags are descriptive.", "",
     "## Summary", "",
     f"Events: {n_ev}; country-event pairs: {len(A)}; outside internal variability: {len(flagged)} "
     f"(pooled binomial reference P(X ≥ {S['pooled']['n_outside']}) = {S['pooled']['p_binom_ge']:.3g} under a 5 % rate).",
     f"Countries flagged in ≥2 events: {int((rep >= 2).sum())}.",
     f"Supply-channel scenario [S] magnitude relative to the no-wind noise half-width: median {A.S_over_noise.median():.2g},"
     f" maximum {A.S_over_noise.max():.2g}.", "",
     "| case | country | ΔP (kg) | ΔP (mm) | ΔP / P_CONTROL | 95 % PI half-width (kg) | z | outside | [S] ΔP (kg) |",
     "|---|---|---|---|---|---|---|---|---|"]
for r in A.sort_values(["case", "country"]).itertuples():
    L.append(f"| {r.case} | {r.country} | {r.dP_wind_kg:.3g} | {r.dP_mm:.3g} | {r.dP_rel:.2g} | {r.pi_halfwidth_kg:.3g} | "
             f"{r.z:.2g} | {r.outside_internal_variability} | {r.S_dP_kg:.3g} |")
open("docs/revision/WRF_SOURCE_RECEPTOR_REPORT.md", "w").write("\n".join(L) + "\n")
print("events", n_ev, "flagged", len(flagged), "max S/noise", A.S_over_noise.max())
