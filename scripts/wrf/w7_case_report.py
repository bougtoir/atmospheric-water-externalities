"""Render WRF case QC and paired-contrast reports (Markdown) from results/wrf/CASE/*.json — no hand-typed values.

Usage: python scripts/wrf/w7_case_report.py CASE OUT_QC.md OUT_EXEC.md
"""
import json, os, sys
import pandas as pd

case, oqc, oex = sys.argv[1:4]
D = f"results/wrf/{case}"; R = f"wrf_runs/{case}"
qc = json.load(open(f"{D}/qc.json")); pr = json.load(open(f"{D}/paired.json"))
cp = pd.read_csv(f"{D}/country_precip.csv") if os.path.getsize(f"{D}/country_precip.csv") > 1 else pd.DataFrame()
timing = open(f"{R}/logs/timing.txt").read().split("\n") if os.path.exists(f"{R}/logs/timing.txt") else []

L = [f"# WRF numeric QC — case `{case}`", "", "Generated by `scripts/wrf/w7_case_report.py` from `results/wrf/%s/qc.json`." % case, ""]
keys = list(next(iter(qc.values())).keys())
L.append("| check | " + " | ".join(qc) + " |"); L.append("|---|" + "---|" * len(qc))
for k in keys:
    L.append(f"| {k} | " + " | ".join(str(qc[e][k]) for e in qc) + " |")
ok = {e: (q["success"] and q["history_frames"] == q["history_frames_expected"] and q["nonfinite_qvapor"] == 0
          and q["negative_qvapor"] == 0 and q["precip_monotone"] and q["cfl_messages"] == 0) for e, q in qc.items()}
L += ["", "Pass rule: SUCCESS COMPLETE WRF, all history frames present at the fixed interval, no non-finite or negative",
      "water vapour, monotone accumulated precipitation, no CFL messages in rsl.error.0000.", ""]
L += [f"- {e}: **{'PASS' if v else 'FAIL'}**" for e, v in ok.items()]
L += ["", "Boundary check: mean accumulated precipitation in the 5-cell relaxation zone versus the next 5 cells inward",
      "(post spin-up) is listed above. A large ratio would indicate a boundary artefact."]
open(oqc, "w").write("\n".join(L) + "\n")

E = [f"# WRF execution and paired contrasts — case `{case}`", "",
     f"Analysis window (after {pr['spinup_h']} h spin-up): {pr['window'][0]} to {pr['window'][1]}.",
     f"Farm cells (grid cells containing ≥1 turbine): {pr['n_farm_cells']}; inner analysis region: {pr['inner_cells']} cells (10-cell boundary margin removed).",
     "", "Wall-clock: " + "; ".join(t for t in timing if t), "",
     "All contrasts are model-conditional differences within this WRF configuration (evidence class [C]).", ""]
for e, st in pr["paired"].items():
    E += [f"## {e} − CONTROL", "", "| field | inner-domain mean Δ | farm-cell mean Δ | inner max |Δ| |", "|---|---|---|---|"]
    for k, v in st.items():
        if isinstance(v, dict) and "domain_inner_mean" in v:
            fm = "n/a" if v["farm_cells_mean"] is None else f"{v['farm_cells_mean']:.4g}"
            E.append(f"| {k} | {v['domain_inner_mean']:.4g} | {fm} | {v['inner_abs_max']:.4g} |")
    for k in ("P_inner_total_kg", "E_inner_total_kg", "E_farm_total_kg"):
        if st.get(k):
            E.append(f"\n{k}: CONTROL {st[k]['control']:.4g} kg; Δ {st[k]['diff']:.4g} kg ({100 * st[k]['diff'] / st[k]['control']:.3g} %)")
    if "mean_power_GW" in st:
        E.append(f"\nMean simulated fleet power: {st['mean_power_GW']:.4g} GW")
    if len(cp):
        c = cp[cp.exp == e].sort_values("dP_kg")
        E += ["", "| country | cells | P CONTROL (kg) | ΔP (kg) | ΔP (mm) | ΔE (kg) |", "|---|---|---|---|---|---|"]
        E += [f"| {r.country} | {r.n_cells} | {r.P_control_kg:.4g} | {r.dP_kg:.4g} | {r.dP_mm:.3g} | {r.dE_kg:.4g} |" for r in c.itertuples()]
    E.append("")
open(oex, "w").write("\n".join(E) + "\n")
print("wrote", oqc, oex)
